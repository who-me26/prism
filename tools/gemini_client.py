"""
Gemini AI Client for PRISM Research Assistant.
Integrates with the official Google GenAI SDK (google-genai v2).
Handles intelligent response generation, multi-source synthesis, citations, and fallback.
"""

import os
from pathlib import Path
from typing import Optional, Dict, Any

try:
    from google import genai
    from google.genai import types
    GENAI_INSTALLED = True
except ImportError:
    GENAI_INSTALLED = False


def _load_env_file():
    """Load GEMINI_API_KEY from .env file if available, without requiring python-dotenv."""
    for base in [Path.cwd(), Path(__file__).parent.parent]:
        env_path = base / ".env"
        if env_path.exists():
            try:
                with open(env_path, "r", encoding="utf-8") as f:
                    for line in f:
                        line = line.strip()
                        if line and not line.startswith("#") and "=" in line:
                            k, v = line.split("=", 1)
                            k, v = k.strip(), v.strip().strip("\"'")
                            if k not in os.environ:
                                os.environ[k] = v
            except Exception:
                pass


_load_env_file()


def get_api_key(passed_key: Optional[str] = None) -> Optional[str]:
    """Retrieve Gemini API key from explicit argument or environment."""
    if passed_key and passed_key.strip():
        return passed_key.strip()
    return os.environ.get("GEMINI_API_KEY", "").strip() or None


def is_gemini_available(api_key: Optional[str] = None) -> bool:
    """Check if Google GenAI SDK is installed and an API key is present."""
    if not GENAI_INSTALLED:
        return False
    key = get_api_key(api_key)
    return bool(key)


def get_client(api_key: Optional[str] = None):
    """Instantiate a google-genai Client."""
    if not GENAI_INSTALLED:
        raise RuntimeError("google-genai package is not installed.")
    key = get_api_key(api_key)
    if not key:
        raise ValueError("GEMINI_API_KEY is not configured.")
    return genai.Client(api_key=key)


def generate_response(
    prompt: str,
    system_instruction: Optional[str] = None,
    model_name: str = "gemini-2.5-flash",
    api_key: Optional[str] = None,
    temperature: float = 0.3,
) -> str:
    """Generate a text response from Gemini AI."""
    if not is_gemini_available(api_key):
        return (
            "⚠️ **Gemini AI Key Not Detected**\n\n"
            "Please provide your Gemini API Key in the sidebar to activate AI reasoning. "
            "You can obtain a free key at [Google AI Studio](https://aistudio.google.com/app/apikey)."
        )

    try:
        client = get_client(api_key)
        config = types.GenerateContentConfig(
            temperature=temperature,
            system_instruction=system_instruction if system_instruction else None,
        )
        response = client.models.generate_content(
            model=model_name,
            contents=prompt,
            config=config,
        )
        return response.text or "No response generated by model."
    except Exception as e:
        return f"❌ **Gemini AI Error**: {str(e)}"


SYSTEM_RESEARCH_PROMPT = """You are PRISM (Predictive & Research Intelligence Synthesis Model), an elite AI research assistant.
Your goal is to provide accurate, context-aware, structured research briefings.
When provided with multi-source context (Wikipedia, arXiv papers, live Weather data), synthesize them intelligently:
1. Executive Summary: High-level distillation answering the user query.
2. Academic & Theoretical Insights (from arXiv): Highlight methodologies, key papers, authors, and breakthroughs.
3. Foundational Knowledge (from Wikipedia): Ground the topic with historical context, core principles, and definitions.
4. Real-World / Environmental Context (if Weather data is relevant): Incorporate live local atmospheric or geographic observations.
5. Key Takeaways & Future Directions: Bullet points outlining implications.
6. Sources & References: Clear citations with hyperlinks.

Maintain an objective, rigorous, professional, and accessible tone. Format with clear Markdown headings, tables, or callouts where helpful.
"""


def synthesize_research(
    query: str,
    wiki_data: Optional[Dict[str, Any]] = None,
    arxiv_data: Optional[Dict[str, Any]] = None,
    weather_data: Optional[Dict[str, Any]] = None,
    api_key: Optional[str] = None,
    model_name: str = "gemini-2.5-flash"
) -> str:
    """
    Synthesize multi-source intelligence from Wikipedia, arXiv, and Weather into a cohesive research report.
    """
    # Build the multi-source context block
    context_sections = []

    if arxiv_data and arxiv_data.get("status") == "success" and arxiv_data.get("papers"):
        context_sections.append(
            f"=== ACADEMIC PAPERS FROM ARXIV ===\n{arxiv_data.get('context_text', '')}"
        )

    if wiki_data and wiki_data.get("status") == "success" and wiki_data.get("articles"):
        context_sections.append(
            f"=== ENCYCLOPEDIC KNOWLEDGE FROM WIKIPEDIA ===\n{wiki_data.get('context_text', '')}"
        )

    if weather_data and weather_data.get("status") == "success":
        context_sections.append(
            f"=== LIVE WEATHER & METEOROLOGICAL DATA ===\n{weather_data.get('summary', '')}"
        )

    context_str = "\n\n".join(context_sections) if context_sections else "No external source data found."

    prompt = (
        f"USER RESEARCH QUERY: {query}\n\n"
        f"RETRIEVED MULTI-SOURCE CONTEXT:\n{context_str}\n\n"
        f"Provide a comprehensive, intelligent research briefing based on the above sources and your general knowledge."
    )

    if not is_gemini_available(api_key):
        # Graceful fallback: format collected results directly
        return _format_fallback_briefing(query, wiki_data, arxiv_data, weather_data)

    return generate_response(
        prompt=prompt,
        system_instruction=SYSTEM_RESEARCH_PROMPT,
        model_name=model_name,
        api_key=api_key,
        temperature=0.25,
    )


def _format_fallback_briefing(
    query: str,
    wiki_data: Optional[Dict[str, Any]],
    arxiv_data: Optional[Dict[str, Any]],
    weather_data: Optional[Dict[str, Any]]
) -> str:
    """Produce a formatted report when Gemini API key is not yet configured."""
    output = [
        f"## 📋 Research Briefing: {query}",
        "> 💡 *Tip: Add your Gemini API key in the sidebar to unlock AI-powered deep synthesis and cross-source reasoning.*\n"
    ]

    if arxiv_data and arxiv_data.get("papers"):
        output.append("### 📚 Academic Research Papers (arXiv)")
        for i, p in enumerate(arxiv_data["papers"], 1):
            output.append(f"**{i}. [{p['title']}]({p['pdf_url']})**")
            output.append(f"*Authors:* {p['authors_str']} | *Published:* {p['published']}")
            output.append(f"> {p['short_summary']}\n")

    if wiki_data and wiki_data.get("articles"):
        output.append("### 🌐 Encyclopedia Overview (Wikipedia)")
        for i, a in enumerate(wiki_data["articles"], 1):
            output.append(f"**{i}. [{a['title']}]({a['url']})**")
            output.append(f"{a['summary']}\n")

    if weather_data and weather_data.get("status") == "success":
        output.append("### ⛅ Live Environmental Data")
        output.append(f"- **Location**: {weather_data.get('location')}")
        output.append(f"- **Condition**: {weather_data.get('condition')} {weather_data.get('emoji')}")
        output.append(f"- **Temperature**: {weather_data.get('temp_c')}°C / {weather_data.get('temp_f')}°F")
        output.append(f"- **Humidity**: {weather_data.get('humidity')}% | **Wind**: {weather_data.get('wind_kmh')} km/h\n")

    if len(output) <= 2:
        output.append("No specific data found for this query across arXiv, Wikipedia, or Weather.")

    return "\n".join(output)
